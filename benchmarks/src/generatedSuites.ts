/**
 * Generates a scaled-up counter `.feature` fixture for a pressure/scale run (ADR-EC-051): a
 * Scenario Outline with N Examples rows, entirely over `fixtures/counter.feature`'s EXISTING step
 * vocabulary — `a new counter bounded between {int} and {int}`, `I increment the counter by {int}`,
 * `the counter value is {int}` — so no new step definitions are needed on either runner.
 */
import * as fs from "node:fs"
import { fromBenchmarkRoot, generatedRoot } from "./paths.ts"

/** High enough that no generated row's increment ever hits the max-bound rejection path. */
const PRESSURE_MAX_BOUND = 10_000_000

// Not exported (ADR-EC-051/knip): `generateScaledCounterFeature` below returns this same path, and
// its caller (`src/compare.ts`) uses that return value rather than importing this constant.
const pressureCounterFeaturePath: string = fromBenchmarkRoot("generated", "pressure-counter.feature")

/** Write `generated/pressure-counter.feature` with `scenarioCount` rows, and return its path. */
export const generateScaledCounterFeature = (scenarioCount: number): string => {
  if (scenarioCount < 1) {
    throw new Error(`generateScaledCounterFeature: scenarioCount must be at least 1, got ${scenarioCount}`)
  }

  const header = "      | amount | value |"
  const rows = Array.from(
    { length: scenarioCount },
    (_unused, index) => {
      const amount = index + 1
      return `      | ${amount} | ${amount} |`
    }
  ).join("\n")

  const feature = `Feature: Pressure counter

  GENERATED by src/generatedSuites.ts — do not hand-edit (ADR-EC-051). A Scenario Outline over
  fixtures/counter.feature's own step vocabulary, scaled to ${scenarioCount} Examples rows, for a
  pressure/scale benchmark run. No tags on purpose, same as the fixture it scales.

  Scenario Outline: Incrementing a fresh counter by <amount> lands on <value>
    Given a new counter bounded between 0 and ${PRESSURE_MAX_BOUND}
    When I increment the counter by <amount>
    Then the counter value is <value>

    Examples:
${header}
${rows}
`

  fs.mkdirSync(generatedRoot, { recursive: true })
  fs.writeFileSync(pressureCounterFeaturePath, feature)
  return pressureCounterFeaturePath
}
